#!/usr/bin/env python3
from __future__ import annotations

import math
import re
from pathlib import Path


ROOT = Path("/home/user/Desktop")
EXPECTED = (14828.440400, 0.801951)
REL_TOL = 2.0e-3
ABS_TOL = 2.0e-5


def read(path: Path) -> str:
    return path.read_text(encoding="utf-8", errors="ignore")


def close(actual: float, expected: float, rel_tol: float = REL_TOL, abs_tol: float = ABS_TOL) -> bool:
    return math.isfinite(actual) and abs(actual - expected) <= max(
        abs_tol, rel_tol * max(1.0, abs(expected))
    )


def parameter(text: str, name: str) -> str:
    match = re.search(rf"^\s*(\S+).*?\s{re.escape(name)}\s+-", text, re.MULTILINE)
    if not match:
        raise ValueError(f"missing parameter {name}")
    return match.group(1).strip('"').rstrip(",")


def check_wind(path: Path) -> bool:
    rows: list[list[float]] = []
    for line in read(path).splitlines():
        if not line.strip() or line.lstrip().startswith("!"):
            continue
        fields = line.split()
        if len(fields) != 8:
            return False
        rows.append([float(value) for value in fields])
    if len(rows) != 601:
        return False
    for index, row in enumerate(rows):
        time = index / 10.0
        speed = 11.4
        if 10.0 <= time <= 20.5:
            speed += 7.5 * (1.0 - math.cos(2.0 * math.pi * (time - 10.0) / 10.5))
        if not close(row[0], time, rel_tol=0.0, abs_tol=1.0e-10):
            return False
        if not close(row[1], speed, rel_tol=0.0, abs_tol=1.0e-7):
            return False
        if any(abs(value) > 1.0e-12 for value in row[2:]):
            return False
    return True


def output_metrics(path: Path) -> tuple[float, float]:
    lines = read(path).splitlines()
    if "at commit v5.0.0" not in "\n".join(lines[:5]):
        raise ValueError("output was not generated by OpenFAST 5.0.0")
    header_index = next(i for i, line in enumerate(lines) if line.split()[:1] == ["Time"])
    headers = lines[header_index].split()
    units = lines[header_index + 1].split()
    time_i = headers.index("Time")
    root_i = headers.index("RootMyb1")
    displacement_i = headers.index("TTDspFA")
    if units[root_i] != "(kN-m)" or units[displacement_i] != "(m)":
        raise ValueError("unexpected native OpenFAST units")
    all_rows: list[list[float]] = []
    for line in lines[header_index + 2 :]:
        fields = line.split()
        if len(fields) != len(headers):
            continue
        try:
            all_rows.append([float(value) for value in fields])
        except ValueError:
            continue
    if len(all_rows) != 601 or not close(all_rows[-1][time_i], 60.0, rel_tol=0.0, abs_tol=1.0e-8):
        raise ValueError("incomplete 60-second output")
    rows = [row for row in all_rows if 10.0 <= row[time_i] <= 30.0]
    if len(rows) != 201:
        raise ValueError("incorrect gust-window sample count")
    return max(abs(row[root_i]) for row in rows), max(abs(row[displacement_i]) for row in rows)


def parse_summary(path: Path) -> tuple[float, float]:
    rows = [line.strip() for line in read(path).splitlines() if line.strip()]
    if len(rows) != 1:
        raise ValueError("summary must contain one row")
    values = tuple(float(field.strip()) for field in rows[0].split(","))
    if len(values) != 2 or not all(math.isfinite(value) for value in values):
        raise ValueError("summary must contain two finite values")
    return values


def check() -> bool:
    required = (
        "build_case.py",
        "postprocess.py",
        "eog.wnd",
        "eog_inflow.dat",
        "elasto_eog.dat",
        "aero_eog.dat",
        "servo_eog.dat",
        "eog_case.fst",
        "eog_case.out",
        "eog_case.log",
        "summary.txt",
    )
    if any(not (ROOT / name).is_file() or (ROOT / name).stat().st_size == 0 for name in required):
        return False
    if not check_wind(ROOT / "eog.wnd"):
        return False

    inflow = read(ROOT / "eog_inflow.dat")
    expected_inflow = {"WindType": "2", "FileName_Uni": "eog.wnd", "RefHt_Uni": "90.0"}
    if any(parameter(inflow, name) != value for name, value in expected_inflow.items()):
        return False

    elasto = read(ROOT / "elasto_eog.dat")
    if '"RootMyb1"' not in elasto or '"TTDspFA"' not in elasto or '"../5MW_Baseline/' in elasto:
        return False
    if '"../5MW_Baseline/' in read(ROOT / "aero_eog.dat") or '"../5MW_Baseline/' in read(ROOT / "servo_eog.dat"):
        return False

    main = read(ROOT / "eog_case.fst")
    expected_main = {
        "TMax": "60.0",
        "DT_Out": "0.1",
        "OutFileFmt": "1",
        "EDFile": "elasto_eog.dat",
        "InflowFile": "eog_inflow.dat",
        "AeroFile": "aero_eog.dat",
        "ServoFile": "servo_eog.dat",
    }
    if any(parameter(main, name) != value for name, value in expected_main.items()):
        return False

    log = read(ROOT / "eog_case.log")
    if "OpenFAST-v5.0.0" not in log or "OpenFAST terminated normally." not in log:
        return False

    calculated = output_metrics(ROOT / "eog_case.out")
    reported = parse_summary(ROOT / "summary.txt")
    return all(close(actual, expected) for actual, expected in zip(calculated, EXPECTED)) and all(
        close(actual, expected) for actual, expected in zip(reported, EXPECTED)
    ) and all(close(actual, value, rel_tol=0.0, abs_tol=2.0e-5) for actual, value in zip(reported, calculated))


def main() -> int:
    try:
        result = check()
    except Exception:
        result = False
    print("True" if result else "False")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
